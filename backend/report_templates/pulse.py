"""Template 4 — 'Pulse': modern SaaS style, colour-coded, chart-forward."""

from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.platypus import (Paragraph, Spacer, Table, TableStyle,
                                HRFlowable)

from .base import (p, para, hbar_chart, severity_of, build, PAGE_W, PAGE_H)

TEMPLATE_ID = "pulse"
TEMPLATE_NAME = "Pulse"
TEMPLATE_DESC = "Modern light theme. Teal header band, colour stat cards, alert timeline, port chart."

TEAL      = colors.HexColor("#0E7C7B")
TEAL_DK   = colors.HexColor("#0A5E5D")
TEAL_BG   = colors.HexColor("#E6F4F3")
RED       = colors.HexColor("#E5484D")
RED_BG    = colors.HexColor("#FDECEC")
AMBER     = colors.HexColor("#E79B13")
AMBER_BG  = colors.HexColor("#FFF6E0")
SLATE     = colors.HexColor("#1F2A37")
SLATE_BG  = colors.HexColor("#EEF1F5")
MUTED     = colors.HexColor("#6B778C")
WHITE     = colors.white


def _header_band(canvas):
    canvas.setFillColor(TEAL_DK)
    canvas.rect(0, PAGE_H - 1.55 * inch, PAGE_W, 1.55 * inch, fill=1, stroke=0)
    canvas.setFillColor(TEAL)
    canvas.rect(0, PAGE_H - 1.62 * inch, PAGE_W, 0.07 * inch, fill=1, stroke=0)
    canvas.setFillColor(WHITE)
    canvas.setFont("Helvetica-Bold", 20)
    canvas.drawString(0.75 * inch, PAGE_H - 0.95 * inch, "PLEXUS")
    canvas.setFont("Helvetica", 10)
    canvas.setFillColor(colors.HexColor("#BFE3E2"))
    canvas.drawString(0.75 * inch, PAGE_H - 1.25 * inch,
                      "Network Threat Report")
    canvas.setFont("Helvetica", 8)
    canvas.drawRightString(PAGE_W - 0.75 * inch, PAGE_H - 1.0 * inch,
                           "CONFIDENTIAL")


def _footer(canvas, doc):
    canvas.setFillColor(MUTED)
    canvas.setFont("Helvetica", 7)
    canvas.drawCentredString(PAGE_W / 2, 0.5 * inch,
                             f"Generated by PLEXUS NIDS  •  page {doc.page}")


def _stat_cards(data):
    crit = sum(1 for a in data["alerts"]
               if severity_of(a["alert_type"]) == "critical")
    cards = [
        (f"{data['packet_count']:,}", "PACKETS", TEAL_BG, TEAL),
        (str(data["alert_count"]), "ALERTS", AMBER_BG, AMBER),
        (str(crit), "CRITICAL", RED_BG, RED),
        (f"{data['port_usage'][0]['dst_port']}", "TOP PORT", SLATE_BG, SLATE),
    ]
    cells = []
    for val, label, bg, fg in cards:
        inner = Table([
            [para(f"<b>{val}</b>",
                  p("n", size=20, color=fg, bold=True, align=1,
                    space_after=1))],
            [para(label, p("l", size=7.5, color=MUTED, align=1,
                           space_after=0))],
        ], colWidths=[1.62 * inch])
        inner.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), bg),
            ("TOPPADDING", (0, 0), (-1, -1), 10),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
        ]))
        cells.append(inner)
    t = Table([cells], colWidths=[1.7 * inch] * 4,
              spaceBefore=4, spaceAfter=4)
    t.setStyle(TableStyle([
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def _timeline(alerts):
    rows = []
    for a in alerts:
        sev = severity_of(a["alert_type"])
        dot_c = "#E5484D" if sev == "critical" else "#E79B13"
        rows.append([
            para(f'<font color="{dot_c}" size="14">●</font>',
                 p("d", align=1, space_after=0)),
            para(f"<b>{a['alert_type']}</b> &nbsp;"
                 f"<font color=\"{dot_c}\"><b>{sev.upper()}</b></font><br/>"
                 f"<font color=\"#6B778C\">{a['timestamp']}  •  {a['src_ip']}</font><br/>"
                 f"{a['description']}",
                 p("b", size=8.5, color=SLATE, leading=12)),
        ])
    t = Table(rows, colWidths=[0.45 * inch, 6.55 * inch])
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LINEBELOW", (0, 0), (-1, -2), 0.5, colors.HexColor("#E3E8F0")),
        ("LEFTPADDING", (1, 0), (1, -1), 6),
    ]))
    return t


def _packet_table(packets):
    rows = [[para(f"<b>{h}</b>", p("h", size=7.5, color=WHITE, bold=True))
             for h in ("TIME", "SOURCE", "DESTINATION", "PORTS", "LEN", "PROTO")]]
    for x in packets[:45]:
        proto_c = {"TCP": "#0E7C7B", "UDP": "#6C5CE7"}.get(
            x["protocol"], "#6B778C")
        rows.append([
            para(x["timestamp"][11:], p("c", size=7, color=MUTED)),
            para(x["src_ip"], p("c", size=7, color=SLATE)),
            para(x["dst_ip"], p("c", size=7, color=SLATE)),
            para(f"{x['src_port']}→{x['dst_port']}",
                 p("c", size=7, color=MUTED)),
            para(str(x["length"]), p("c", size=7, color=MUTED)),
            para(f'<font color="{proto_c}"><b>{x["protocol"]}</b></font>',
                 p("c", size=7, bold=True)),
        ])
    t = Table(rows, colWidths=[0.85 * inch, 1.35 * inch, 1.35 * inch,
                               1.25 * inch, 0.6 * inch, 0.6 * inch])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), SLATE),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [WHITE, colors.HexColor("#F4F7F9")]),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
    ]))
    return t


def _elements(data):
    el = []
    el.append(Spacer(1, 0.55 * inch))
    el.append(para(f"Session <b>{data['session_id']}</b> &nbsp;·&nbsp; "
                   f"{data['started_at']} → {data['ended_at']} &nbsp;·&nbsp; "
                   f"{data['iface']}",
                   p("me", size=9, color=MUTED, space_after=8)))
    el.append(_stat_cards(data))
    el.append(Spacer(1, 0.08 * inch))

    el.append(para("Alert timeline", p("s1", size=13, color=SLATE, bold=True,
                                       space_before=8, space_after=2)))
    el.append(HRFlowable(width="100%", thickness=1.5, color=TEAL,
                         spaceAfter=4))
    el.append(_timeline(data["alerts"]))

    el.append(para("Port activity", p("s2", size=13, color=SLATE, bold=True,
                                    space_before=10, space_after=6)))
    el.append(HRFlowable(width="100%", thickness=1.5, color=TEAL,
                         spaceAfter=8))
    el.append(hbar_chart(
        [(f":{r['dst_port']}", r["count"]) for r in data["port_usage"]],
        bar_color=TEAL, label_color=SLATE, value_color=MUTED))

    el.append(para("Packet sample", p("s3", size=13, color=SLATE, bold=True,
                                     space_before=12, space_after=6)))
    el.append(HRFlowable(width="100%", thickness=1.5, color=TEAL,
                         spaceAfter=8))
    el.append(_packet_table(data["packets"]))
    return el


def _generate(data):
    return _elements(data), {
        "bg_painter": None, "footer": _footer, "top": 1.85 * inch,
    }


def _band_first_page(canvas, doc):
    if doc.page == 1:
        _header_band(canvas)


def _generate2(data):
    elements, kw = _generate(data)
    orig_footer = kw["footer"]

    def footer(canvas, doc):
        _band_first_page(canvas, doc)
        orig_footer(canvas, doc)
    kw["footer"] = footer
    return elements, kw


generate = build(_generate2)
